#define _CRT_SECURE_NO_WARNINGS															/* Разрешение использовать scanf */
#include <stdio.h>																		/* Подключение стандартных модулей ввода и вывода */
#include <windows.h>																	/* Подключение объявлений функций Windows */

/* begin */
int main(void)																			/* Тело программы */
{
	SetConsoleOutputCP(CP_UTF8);														/* Установка вывода консоли в кодовой странице UTF-8 */

	printf("Лабораторная работа 1\nЗадание N№18\n\n");									/* Номер лабораторной работы и номер задания */
	printf("Задание: \nСеликционер вывел новый сорт зерновых и снял с опытного ");		/* Условие задачи */
	printf("участка К кг семян. Посеяв 1 кг семян, можно за сезон собрать Р кг семян. ");
	printf("Через сколько лет новой культурой можно засеять поле площадью S га, если ");
	printf("норма высева N кг/га?\n\n");

	char will_repeat = 'Y';																/* Переменная для повторения кода программы */
	while (will_repeat == 'Y')															/* Цикл для повторения кода программы */
	{
		/* Инициализация переменных */
		int t = 0;																		/* Переменная, для подсчёта времени */
		int M = 0;																		/* Переменные, для промежуточных вычислений */
		int K = 0;
		int S = 0;
		int N = 0;
		int P = 0;
		int K2, K3;

		printf("Введите К - исходный запас семян: ");									/* Ввод K - исходного запаса семян */
		scanf("%d", &K);

		printf("Введите S - площадь поля: ");											/* Ввод S - площади поля */
		scanf("%d", &S);													

		printf("Введите N - норму высева: ");											/* Ввод N - нормы высева */
		scanf("%d", &N);

		printf("Введите P - урожай за сезон: ");										/* Ввод P - урожай за сезон */
		scanf("%d", &P);

		M = S * N;																		/* Вычисление M - требуемого количества семян для засева всего поля */
		printf("\nНеобходимо семян чтобы засеять всё поле: %d кг\n\n", M);
		printf("Сколько понадобится лет чтобы засеять всё поле?\n");

		if (P > 1 && K > 0 && S > 0 && N > 0)																/* Если P - урожай за сезон < 0, то в итоге поле не будет засеяно */
		{
			K2 = K;																		/* Присваивание переменной для подсчёта внутри цикла значение K  */

			while (K2 < M)																/* Условие цикла: пока запас семян меньше требуемого кол-ва семян */
			{																			/* для засева всего поля - повторяем решение. */

				K2 *= P;																/* Исходный запас семян прибавляет урожай за сезон */
				t++;																	/* Счётчик считает сколько лет проходит */
				printf("\nПрошло лет: %d, накопилось семян: %d кг\n", t, K2);
			}

			if (P > 1)																	/* Повторное решение для вывода таблицы*/
			{	
				K3 = K;																	/* Присваивание переменной для подсчёта внутри цикла значение K */
				t = 0;																	/* Счётчик обнулить, чтобы заново провести вычисления */

				printf("\n\nХод решения:\n\n");											/* Фиксированное начало таблицы с результатами решения */
				printf("|===|=========|=====|=======|\n");
				printf("| t |  K * P  |  K  | K > M |\n");
				printf("|===|=========|=====|=======|\n");

				while (K3 < M)															/* Цикл для вывода результатов в таблицу. Условие цикла: пока запас семян */
				{																		/* меньше требуемого кол-ва семян для засева всего поля - повторяем решение. */
					K3 *= P;															/* Исходный запас семян прибавляет урожай за сезон */
					t++;																/* Счётчик считает сколько лет проходит */
					printf("| %d | %3d * %d | %3d | %5d |\n", t, K3, P, K3 * P, K3 > M);
				}
				printf("|===|=========|=====|=======|\n\n");

				printf("t - количество лет\n");
				printf("K - количество семян\n");
				printf("P - урожай за сезон\n");
				printf("M - кол-во семня необходимое для засева поля\n");
			}

			printf("\nОтвет:\n");
			printf("Понадобится %d лет чтобы засеять поле площадью %d га новой культурой, если норма высева %d кг/га\n\n", t, S, N);
		
		}

		/* Отработка варианта запаса семян изначально достаточно */
		if (K > 0 && P <= 1  && S > 0 && N > 0)
		{
			if (K >= M)
			{
				printf("Семян уже достаточно чтобы засеять всё поле! Понадобится %d лет.\n", t);
			}
			else if (K < M)
			{
				printf("Семян недостаточно чтобы засеять всё поле! Урожайность низкая, запас семян не вырастет!\n");
			}
		}

        /* Отработка вариант когда запас семян отрицательный или равен нулю */
		if (K < 0)
		{
			printf("Отрицательного запаса семян не может быть\n");
		}

		if (K == 0)
		{
			printf("Нечего сажать, исходный запас зерна равен нулю!\n");
		}

		/* Отработка варианта когда площадь поля отрицательная или равна нулю */
		if (S <= 0)
		{
			printf("Негде сажать! Площадь поля не соответсвтует принятому ограничению.\n");
		}

		/* Отработка варианта когда норма высева отрицательная или равна нулю */
		if (N <= 0)
		{
			printf("Нельзя сеять! Норма высева не соответсвует принятому ограничению.\n");
		}
		
		/* Предложение повторить алгоритм */
		printf("Повторить вычисления? Y/N: ");
		scanf(" %c", &will_repeat);
	}

	return 0;
}


